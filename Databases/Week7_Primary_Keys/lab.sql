-- Week 7: Primary Keys
-- Topics: what a primary key is, the three ways to declare one, adding one
--         to an existing table, single vs composite keys, SERIAL / BIGSERIAL /
--         IDENTITY, and the constraints PostgreSQL enforces automatically.
--
-- Run with:
--   psql -h localhost -p 1569 -U ulan -d ulan -f lab.sql


DROP TABLE IF EXISTS course_enrollments, students, products, transactions,
                     orders, customers, departments, no_key;


-- ============================================================
-- 1. Three ways to declare a primary key
-- ============================================================

-- Method 1: column-level constraint
CREATE TABLE students (
    student_id INTEGER PRIMARY KEY,
    name       VARCHAR(100),
    email      VARCHAR(150)
);
\d students
DROP TABLE students;

-- Method 2: table-level constraint -- identical result
CREATE TABLE students (
    student_id INTEGER,
    name       VARCHAR(100),
    email      VARCHAR(150),
    PRIMARY KEY (student_id)
);
\d students
DROP TABLE students;

-- Method 3: named constraint -- the only difference is the constraint name,
-- "pk_students" instead of the auto-generated "students_pkey"
CREATE TABLE students (
    student_id INTEGER,
    name       VARCHAR(100),
    email      VARCHAR(150),
    CONSTRAINT pk_students PRIMARY KEY (student_id)
);
\d students
DROP TABLE students;


-- ============================================================
-- 2. Adding a primary key to an existing table
-- ============================================================
CREATE TABLE no_key (
    student_id INTEGER NOT NULL,
    name       VARCHAR(100)
);

ALTER TABLE no_key ADD CONSTRAINT pk_no_key PRIMARY KEY (student_id);
\d no_key


-- ============================================================
-- 3. Single primary key
-- ============================================================
CREATE TABLE students (
    student_id SERIAL PRIMARY KEY,
    name       VARCHAR(100) NOT NULL,
    email      VARCHAR(150) UNIQUE,
    faculty    VARCHAR(50)
);

INSERT INTO students (name, email, faculty) VALUES
('Alice Johnson', 'alice@alatoo.edu.kg', 'Computer Science'),
('Bob Smith',     'bob@alatoo.edu.kg',   'Mathematics'),
('Carol Davis',   'carol@alatoo.edu.kg', 'Computer Science');

SELECT * FROM students;


-- ============================================================
-- 4. Composite primary key
-- ============================================================
-- No single column is unique here: a student takes many courses, a course
-- has many students, and both repeat across semesters. The three columns
-- together are what identifies a row.

CREATE TABLE course_enrollments (
    student_id      INTEGER,
    course_id       INTEGER,
    semester        VARCHAR(20),
    enrollment_date DATE DEFAULT CURRENT_DATE,
    grade           CHAR(2),
    PRIMARY KEY (student_id, course_id, semester)
);

INSERT INTO course_enrollments (student_id, course_id, semester, grade) VALUES
(1, 101, '2024-Spring', 'A'),
(1, 102, '2024-Spring', 'B+'),
(2, 101, '2024-Spring', 'A-'),
(1, 101, '2024-Fall',   'A+');  -- same student, same course, other semester -- OK

SELECT * FROM course_enrollments;
\d course_enrollments

-- FAILS: all three columns repeat the first row
INSERT INTO course_enrollments (student_id, course_id, semester, grade)
VALUES (1, 101, '2024-Spring', 'B');


-- ============================================================
-- 5. Auto-generated keys (PostgreSQL's AUTO_INCREMENT)
-- ============================================================

-- SERIAL = INTEGER + a sequence + DEFAULT nextval(...)
CREATE TABLE products (
    product_id   SERIAL PRIMARY KEY,
    product_name VARCHAR(100) NOT NULL,
    price        DECIMAL(10,2)
);
\d products

-- BIGSERIAL: same idea, 8-byte integers for very large tables
CREATE TABLE transactions (
    transaction_id   BIGSERIAL PRIMARY KEY,
    amount           DECIMAL(15,2),
    transaction_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- IDENTITY ALWAYS: PostgreSQL owns the value completely
CREATE TABLE orders (
    order_id      INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    customer_name VARCHAR(100),
    order_date    DATE DEFAULT CURRENT_DATE
);

INSERT INTO orders (customer_name) VALUES ('Alice Johnson'), ('Bob Smith');
SELECT * FROM orders;

-- FAILS: you may not supply order_id yourself with ALWAYS
INSERT INTO orders (order_id, customer_name) VALUES (99, 'Hacker');

-- IDENTITY BY DEFAULT: generated unless you supply a value
CREATE TABLE customers (
    customer_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name VARCHAR(100),
    email         VARCHAR(150)
);

INSERT INTO customers (customer_name, email)
VALUES ('Regular Customer', 'regular@example.com');

-- this one is allowed
INSERT INTO customers (customer_id, customer_name, email)
VALUES (1000, 'VIP Customer', 'vip@example.com');

SELECT * FROM customers;


-- ============================================================
-- 6. What a primary key enforces automatically
-- ============================================================
CREATE TABLE departments (
    dept_id   INTEGER PRIMARY KEY,
    dept_name VARCHAR(100)
);

INSERT INTO departments VALUES (1, 'Computer Science');

-- UNIQUE: FAILS, dept_id 1 is taken
INSERT INTO departments VALUES (1, 'Mathematics');

-- NOT NULL: FAILS, a primary key can never be NULL
INSERT INTO departments VALUES (NULL, 'Physics');

-- Automatic index: PostgreSQL built a unique B-tree index for the key,
-- which is why lookups and joins on it are fast.
SELECT indexname, indexdef FROM pg_indexes WHERE tablename = 'departments';


-- ============================================================
-- clean up
-- ============================================================
DROP TABLE course_enrollments, students, products, transactions,
           orders, customers, departments, no_key;
\dt
